# mu-law (8 bit) decoder, for the delay lines
def mulaw_dec(b):
    b = ~b & 0xFF
    sign = b & 0x80
    exp = (b >> 4) & 7
    man = b & 15
    v = ((man << 3) + 0x84) << exp
    v -= 0x84
    return -v if sign else v
out.append(arr("T_MULAW", "int16_t", [clamp(mulaw_dec(b), -32767, 32767) for b in range(256)]))


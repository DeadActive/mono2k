# 8x8 Bayer matrix, 0..63
def bayer(n):
    if n == 1:
        return [[0]]
    b = bayer(n // 2)
    m = n // 2
    r = [[0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            r[y][x] = 4 * b[y % m][x % m] + [[0, 2], [3, 1]][y // m][x // m]
    return r
B = bayer(8)
out.append("static const uint8_t T_BAYER[8][8] = {%s};\n" % ", ".join("{" + ", ".join(map(str, row)) + "}" for row in B))


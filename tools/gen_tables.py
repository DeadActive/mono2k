# MONO2K's lookup tables: everything the integer DSP would otherwise need floating point for.
# Writes firmware/gen/m2k_tables.h.
import math, os, sys, random

SR = 44100
SUB = 16
OUT = os.path.join(os.path.dirname(__file__), "..", "firmware", "gen", "m2k_tables.h")


def arr(name, ctype, vals, per=12):
    s = "static const %s %s[%d] = {\n" % (ctype, name, len(vals))
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


out = ["/* generated by tools/gen_tables.py: do not edit */\n#include <stdint.h>\n"]

# sine, 1024 + guard, full scale 32767
out.append(arr("T_SIN", "int16_t", [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]))

# phase increments for the top octave (MIDI 120..132) in 1/64 semitones; lower octaves shift right
top = []
for i in range(769):
    f = 440.0 * 2 ** ((120 + i / 64.0 - 69) / 12.0)
    top.append(min(0xFFFFFFFF, round(f / SR * 2 ** 32)))
out.append(arr("T_INC_TOP", "uint32_t", top, 8))

# envelope times: t(v) = 1 ms * 2^(v / 10); 0 is ~0.3 ms
def etime(v):
    return 0.0003 if v == 0 else 0.001 * 2 ** (v / 10.0)
# linear rise per control block, full scale 2^30
out.append(arr("T_ENV_INC", "uint32_t", [min(1 << 30, round((1 << 30) * SUB / (etime(v) * SR))) for v in range(128)], 8))
# exponential fall per control block to -60 dB in t(v), Q31 multiplier
out.append(arr("T_ENV_COEF", "uint32_t",
               [round((2 ** 31 - 1) * math.exp(-6.9078 * SUB / (etime(v) * SR))) for v in range(128)], 8))
# the times as the screen shows them, in ms (0.1 ms below 10)
out.append(arr("T_ENV_MS10", "uint32_t", [round(etime(v) * 10000) for v in range(128)], 8))

# the amp envelope, after the Monomachine's, measured on OS 1.32B in gearmulator (tools/ref, amp.spec, hold.spec):
#   the attack rises in a straight line, in 0.90 ms * e^(0.0814 v); decay and release fall 20 dB in 8.3 ms * e^(0.0665 v)
#   (here: to -60 dB, three times that); the hold lasts 14.6 ms a step. 127: hold and decay last while the gate is open.
def a_atk(v):
    return 0.000903 * math.exp(0.0814 * v)
def a_dec(v):
    return 3 * 0.00829 * math.exp(0.06646 * v)
def a_hold(v):
    return 0.0146 * v
out.append(arr("T_AATK_INC", "uint32_t", [min(1 << 30, round((1 << 30) * SUB / (a_atk(v) * SR))) for v in range(128)], 8))
out.append(arr("T_ADEC_COEF", "uint32_t", [round((2 ** 31 - 1) * math.exp(-6.9078 * SUB / (a_dec(v) * SR))) for v in range(128)], 8))
out.append(arr("T_AHOLD", "uint32_t", [round(a_hold(v) * SR / SUB) for v in range(128)], 8))
out.append(arr("T_AATK_MS10", "uint32_t", [round(a_atk(v) * 10000) for v in range(128)], 8))
out.append(arr("T_ADEC_MS10", "uint32_t", [round(a_dec(v) * 10000) for v in range(128)], 8))
out.append(arr("T_AHLD_MS10", "uint32_t", [round(a_hold(v) * 10000) for v in range(128)], 8))
# the modulation effect's sweep: 0.1 Hz .. 10 Hz, as a phase step per sample, and for the screen in 0.1 Hz
def mod_hz(v):
    return 0.1 * 100 ** (v / 127.0)
out.append(arr("T_MOD_INC", "uint32_t", [round(mod_hz(v) / SR * 2 ** 32) for v in range(128)], 8))
out.append(arr("T_MOD_HZ10", "uint16_t", [max(1, round(mod_hz(v) * 10)) for v in range(128)]))
# patterns saved before (version 1) timed ATK HOLD DEC REL on etime(): each value to the one nearest its time
def nearest(t, f, lo=0, hi=126):
    return min(range(lo, hi + 1), key=lambda v: abs(math.log(max(f(v), 1e-6)) - math.log(max(t, 1e-6))))
v1 = [[nearest(etime(v), a_atk) for v in range(128)],
      [0 if v == 0 else 127 if v == 127 else nearest(etime(v), a_hold, 1) for v in range(128)],
      [127 if v == 127 else nearest(etime(v), a_dec) for v in range(128)],
      [nearest(etime(v), a_dec) for v in range(128)]]
out.append("static const uint8_t T_AMPV1[4][128] = {\n" + "".join("    {" + ",".join(str(x) for x in r) + "},\n" for r in v1) + "};\n")
# portamento: per control block, Q16 share of the distance left
out.append(arr("T_GLIDE", "uint16_t",
               [65535 if v == 0 else round(65536 * (1 - math.exp(-SUB / (0.0008 * 2 ** (v / 13.0) * SR)))) for v in range(128)]))

# filter cutoff: v (0..127, in 1/8 steps) -> 20 Hz .. 20 kHz; ZDF g = tan(pi fc / fs) in Q12, clamped below Nyquist
def fcut(q3):
    return 20.0 * 1000 ** (q3 / (127 * 8.0))
g = []
for q3 in range(127 * 8 + 1):
    fc = min(fcut(q3), 0.46 * SR)
    g.append(clamp(round(4096 * math.tan(math.pi * fc / SR)), 1, 32767))
out.append(arr("T_CUT_G", "uint16_t", g))
# the cutoff as the screen shows it, Hz
out.append(arr("T_HZ", "uint16_t", [round(fcut(v * 8)) for v in range(128)]))
# one-pole lowpass coefficient (Q15) for a cutoff step v at half rate (the delay lines and the bus)
out.append(arr("T_OP_H", "uint16_t", [round(32767 * (1 - math.exp(-2 * math.pi * min(fcut(v * 8), 10000) / (SR / 2)))) for v in range(128)]))
# and at full rate
out.append(arr("T_OP", "uint16_t", [round(32767 * (1 - math.exp(-2 * math.pi * min(fcut(v * 8), 20000) / SR))) for v in range(128)]))
# resonance: damping R in Q12, from 1.0 (flat) to 0.025 (ringing)
out.append(arr("T_RES_R", "uint16_t", [round(4096 * (1.0 * (0.025 / 1.0) ** (v / 127.0))) for v in range(128)]))

# soft saturation: input -131072..131072 in 257 steps of 1024, unity gain at zero, tanh shape
out.append(arr("T_SAT", "int16_t", [round(32767 * math.tanh((i - 128) / 32.0)) for i in range(257)]))

# constant-power pan, Q15
out.append(arr("T_PAN", "uint16_t", [round(32767 * math.cos(v / 127.0 * math.pi / 2)) for v in range(128)]))
# volume curve (squared), Q15
out.append(arr("T_VOL", "uint16_t", [round(32767 * (v / 127.0) ** 2) for v in range(128)]))

# FM ratios (Q8) and their names; inharmonic ones for the metallic sounds
ratios = [0.25, 0.5, 0.75, 1.0, 1.41, 1.5, 2.0, 2.5, 2.76, 3.0, 3.5, 4.0, 4.24, 5.0, 5.4, 6.0,
          7.0, 7.07, 8.0, 9.0, 10.0, 11.0, 12.0, 13.0, 14.0, 15.0, 15.7, 16.0, 18.0, 20.0, 24.0, 32.0]
out.append(arr("T_RATIO", "uint16_t", [round(r * 256) for r in ratios]))
out.append("static const char *const T_RATIO_NAME[32] = {%s};\n" %
           ", ".join('"%s"' % (("%.2f" % r) if r < 10 else ("%.1f" % r)) for r in ratios))
# FM depth: index 0..14 rad, curved; phase offset per unit (Q15 amplitude) of the modulator
def idx(v):
    return 14.0 * (v / 127.0) ** 2.2
out.append(arr("T_FMK", "uint32_t", [round(idx(v) / (2 * math.pi) * 2 ** 17) for v in range(128)], 8))

# mu-law (8 bit) decoder, for the delay lines
def mulaw_dec(b):
    b = ~b & 0xFF
    sign = b & 0x80
    exp = (b >> 4) & 7
    man = b & 15
    v = ((man << 3) + 0x84) << exp
    v -= 0x84
    return -v if sign else v
out.append(arr("T_MULAW", "int16_t", [clamp(mulaw_dec(b), -32767, 32767) for b in range(256)]))

# IMA ADPCM
steps = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
         107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
         876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428,
         4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350,
         22385, 24623, 27086, 29794, 32767]
out.append(arr("T_ADPCM_STEP", "int16_t", steps))

# vowels: F1 F2 F3 (Hz) -> cutoff index (Q3), and levels (Q8). A E I O U, then the in-betweens
vowels = [("A", 800, 1150, 2900), ("AE", 660, 1700, 2400), ("E", 400, 2100, 2800), ("I", 280, 2400, 3200),
          ("Y", 300, 1800, 2400), ("O", 450, 800, 2830), ("U", 325, 700, 2530), ("ER", 500, 1350, 1700)]
def q3(f):
    return clamp(round(127 * 8 * math.log(f / 20.0) / math.log(1000.0)), 0, 1016)
out.append("static const uint16_t T_VOWEL[8][3] = {%s};\n" %
           ", ".join("{%d, %d, %d}" % (q3(a), q3(b), q3(c)) for _, a, b, c in vowels))
out.append("static const char *const T_VOWEL_NAME[8] = {%s};\n" % ", ".join('"%s"' % v[0] for v in vowels))

# single-cycle waves for WAV-PRO: 32 x 256, int16. Additive spectra, some digital
rnd = random.Random(2000)
waves, names = [], []
def add(name, harm):          # harm: list of (n, amp, phase)
    w = [0.0] * 256
    for n, a, p in harm:
        if n >= 100:
            continue
        for i in range(256):
            w[i] += a * math.sin(2 * math.pi * n * i / 256 + p)
    m = max(1e-9, max(abs(x) for x in w))
    waves.append([round(32000 * x / m) for x in w])
    names.append(name)
add("SINE", [(1, 1, 0)])
add("SAW", [(n, 1 / n, 0) for n in range(1, 64)])
add("SQR", [(n, 1 / n, 0) for n in range(1, 64, 2)])
add("TRI", [(n, (1 / n ** 2) * (1 if (n // 2) % 2 == 0 else -1), 0) for n in range(1, 40, 2)])
add("ORGN", [(1, 1, 0), (2, .7, 0), (3, .5, 0), (4, .3, 0), (6, .25, 0), (8, .2, 0)])
add("BELL", [(1, 1, 0), (2.0, .5, 0), (3, .45, .3), (5, .3, 0), (7, .25, 1), (9, .2, 0), (11, .15, 0)])
add("GLAS", [(1, .6, 0), (4, 1, 0), (7, .6, 0), (11, .4, 0), (13, .3, 0)])
add("PLST", [(n, (1 / n) * (2.5 if n in (5, 6, 7) else 1), 0) for n in range(1, 32)])
add("LTEX", [(n, (1 / n) * math.exp(-((n - 9) ** 2) / 8.0) * 3 + (1 / n ** 2), 0) for n in range(1, 40)])
add("CHRM", [(n, 1 / math.sqrt(n), n * n * 0.7) for n in range(1, 48)])
add("HOLW", [(n, 1 / n, 0) for n in range(1, 30, 3)])
add("NASL", [(n, math.exp(-((n - 3) ** 2) / 2.0) + .2 / n, 0) for n in range(1, 24)])
add("VOXA", [(n, math.exp(-((n * 110 - 800) ** 2) / 60000.0) + .7 * math.exp(-((n * 110 - 1150) ** 2) / 80000.0) + .05 / n, 0) for n in range(1, 40)])
add("VOXO", [(n, math.exp(-((n * 110 - 450) ** 2) / 40000.0) + .6 * math.exp(-((n * 110 - 800) ** 2) / 50000.0) + .05 / n, 0) for n in range(1, 40)])
add("VOXI", [(n, math.exp(-((n * 110 - 280) ** 2) / 20000.0) + .5 * math.exp(-((n * 110 - 2400) ** 2) / 200000.0) + .05 / n, 0) for n in range(1, 40)])
add("BUZZ", [(n, 1.0, 0) for n in range(1, 40)])
add("PULS", [(n, math.sin(math.pi * n * 0.15) / n, 0) for n in range(1, 64)])
add("FORM", [(n, 1 / n * (1 + 4 * math.exp(-((n - 12) ** 2) / 3.0)), 0) for n in range(1, 48)])
add("STRG", [(n, (1 / n) * (1 + .5 * math.sin(n)), 0) for n in range(1, 48)])
add("MTL1", [(n, rnd.random() / math.sqrt(n), rnd.random() * 6.28) for n in (1, 3, 4, 7, 9, 13, 17, 23)])
add("MTL2", [(n, rnd.random() / math.sqrt(n), rnd.random() * 6.28) for n in (1, 2, 5, 8, 11, 16, 21, 29, 37)])
add("ODD8", [(n, 1 / n, 0) for n in range(1, 17, 2)])
add("EVEN", [(n, 1 / n, 0) for n in [1] + list(range(2, 32, 2))])
add("RAMP", [(n, (1 / n) * (-1) ** n, 0) for n in range(1, 8)])
# digital ones: built in the time domain
def addt(name, f):
    waves.append([clamp(round(32000 * f(i / 256.0)), -32767, 32767) for i in range(256)])
    names.append(name)
addt("STEP", lambda t: [-1, -.5, 0, .5, 1, .5, 0, -.5][int(t * 8)])
addt("BITS", lambda t: 1 if (int(t * 256) * 37) & 64 else -1)
addt("8BIT", lambda t: (round(math.sin(2 * math.pi * t) * 3) / 3.0))
addt("SID1", lambda t: (((int(t * 4096)) & (int(t * 4096) >> 1)) % 4096) / 2048.0 - 1)
addt("KNIF", lambda t: (1 - 2 * t) ** 7)
addt("SPIK", lambda t: math.exp(-40 * t) * 2 - 1 if t < 0.5 else -math.exp(-40 * (t - .5)) * 2 + 1)
addt("CRSH", lambda t: math.copysign(abs(math.sin(2 * math.pi * t)) ** .2, math.sin(2 * math.pi * t)))
addt("NOIZ", lambda t, r=[rnd.uniform(-1, 1) for _ in range(256)]: r[int(t * 256)])
assert len(waves) == 32, len(waves)
flat = [v for w in waves for v in w]
out.append(arr("T_WAVES", "int16_t", flat, 16))
out.append("static const char *const T_WAVE_NAME[32] = {%s};\n" % ", ".join('"%s"' % n for n in names))

# 8x8 Bayer matrix, 0..63
def bayer(n):
    if n == 1:
        return [[0]]
    b = bayer(n // 2)
    m = n // 2
    r = [[0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            r[y][x] = 4 * b[y % m][x % m] + [[0, 2], [3, 1]][y // m][x // m]
    return r
B = bayer(8)
out.append("static const uint8_t T_BAYER[8][8] = {%s};\n" % ", ".join("{" + ", ".join(map(str, row)) + "}" for row in B))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("".join(out))
print("wrote", os.path.normpath(OUT))

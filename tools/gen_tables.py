# single-cycle waves for WAV-PRO: 32 x 256, int16. Additive spectra, some digital
rnd = random.Random(2000)
waves, names = [], []
def add(name, harm):          # harm: list of (n, amp, phase)
    w = [0.0] * 256
    for n, a, p in harm:
        if n >= 100:
            continue
        for i in range(256):
            w[i] += a * math.sin(2 * math.pi * n * i / 256 + p)
    m = max(1e-9, max(abs(x) for x in w))
    waves.append([round(32000 * x / m) for x in w])
    names.append(name)
add("SINE", [(1, 1, 0)])

# digital ones: built in the time domain
def addt(name, f):
    waves.append([clamp(round(32000 * f(i / 256.0)), -32767, 32767) for i in range(256)])
    names.append(name)
addt("STEP", lambda t: [-1, -.5, 0, .5, 1, .5, 0, -.5][int(t * 8)])
addt("BITS", lambda t: 1 if (int(t * 256) * 37) & 64 else -1)

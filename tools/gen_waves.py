# The owner's 64 waves (assets/waves/mono2k64/OSC-1..64.wav, kept as they are) into the device's format: 64 cycles of
# 256 signed 16-bit samples, as MONO2K's own 32 (firmware/gen/m2k_waves64.h). The steps, each wave alike:
#   1. read the file as it is (16-bit PCM; its first channel)
#   2. its whole cycles, from its spectrum (tools/wave_audit.py): one, but for a file whose harmonics all sit on
#      multiples of m (m cycles in it), whose spectrum is read at those bins, one cycle out of m: a correction,
#      recorded (OSC-20: five)
#   3. one cycle's spectrum resampled to 256 points: the DFT of the file, harmonics 1..127 (the most 256 samples
#      carry; a longer file's higher ones are dropped, their energy recorded), DC kept as it is, the inverse DFT at
#      256: an exact, band-limited periodic resampling. Loop jumps are kept, as the band limit draws them
#   4. scaled to MONO2K's bank's peak, 32000 (the files peak at -0.1 dBFS; band-limiting a jump overshoots, so each
#      is scaled from its own peak after resampling; the scale recorded)
#   5. rounded to 16 bits
# Nothing is hand-edited. Writes the header and the processing table (assets/waves/mono2k64/PROCESSING.md).
#   .venv/bin/python tools/gen_waves.py
import os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
from wave_audit import read, cycles

SRC = os.path.join(ROOT, "assets", "waves", "mono2k64")
OUT = os.path.join(ROOT, "firmware", "gen", "m2k_waves64.h")
N, H, PEAK = 256, 127, 32000


def convert(path):
    x, ch, bits, rate, n = read(path)
    m, share = cycles(x)
    X = np.fft.rfft(x)
    harm = np.arange(1, len(X)) // m if m > 1 else np.arange(1, len(X))
    Y = np.zeros(N // 2 + 1, complex)
    Y[0] = X[0] * N / n                                   # DC as it is
    kept = 0
    for k in range(1, H + 1):
        b = k * m
        if b >= len(X) or (n % 2 == 0 and b == n // 2):
            break
        Y[k] = X[b] * N / n
        kept = k
    tot = np.sum(np.abs(X[1:]) ** 2)
    on = np.sum(np.abs(X[m::m][:kept]) ** 2) if m > 1 else np.sum(np.abs(X[1:kept + 1]) ** 2)
    dropped = 10 * np.log10(max(tot - on, 1e-30) / tot) if tot > 0 else -300
    y = np.fft.irfft(Y, N)
    peak0 = np.abs(x).max()
    scale = PEAK / np.abs(y).max()
    q = np.clip(np.round(y * scale), -32767, 32767).astype(int)
    return q, dict(n=n, m=m, kept=kept, dropped_db=float(dropped), dc=float(x.mean()), over_db=float(20 * np.log10(np.abs(y).max() / peak0)),
                   scale_db=float(20 * np.log10(scale * peak0 / 32768)))


def main():
    waves, notes = [], []
    for i in range(1, 65):
        q, info = convert(os.path.join(SRC, f"OSC-{i}.wav"))
        waves.append(q)
        notes.append((i, info))
    flat = [int(v) for w in waves for v in w]
    with open(OUT, "w") as f:
        f.write("/* generated by tools/gen_waves.py from assets/waves/mono2k64 (the owner's waves): do not edit */\n")
        f.write("static const int16_t T_WAVES64[64 * 256] = {\n")
        for j in range(0, len(flat), 16):
            f.write("    " + ", ".join(str(v) for v in flat[j:j + 16]) + ",\n")
        f.write("};\n")
        f.write("static const char *const T_WAVE64_NAME[64] = {%s};\n" % ", ".join('"OS%02d"' % i for i in range(1, 65)))
    lines = ["# The 64-wave bank: processing", "",
             "From each original (`OSC-N.wav`, kept as it is) to the device's cycle of 256 16-bit samples, by",
             "`tools/gen_waves.py` (its header lists the steps). Per wave: the file's length; its whole cycles (one,",
             "or m: the spectrum read at multiples of m, a correction); the harmonics kept (up to 127); the energy of",
             "those dropped above them; the band limit's overshoot of the original peak; the level the bank's 32000",
             "peak gives against the file's (dB).", "",
             "| Wave | Length | Cycles | Harmonics kept | Dropped energy | Overshoot | Level | Note |", "|---|---|---|---|---|---|---|---|"]
    for i, d in notes:
        note = f"**corrected**: {d['m']} whole cycles in the file, one taken" if d["m"] > 1 else ""
        lines.append(f"| OS{i:02d} (OSC-{i}) | {d['n']} | {d['m']} | {d['kept']} | "
                     f"{'none' if d['dropped_db'] < -120 else '%.1f dB' % d['dropped_db']} | {d['over_db']:+.2f} dB | {d['scale_db']:+.2f} dB | {note} |")
    with open(os.path.join(SRC, "PROCESSING.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"64 waves into {os.path.relpath(OUT, ROOT)}; corrected: {[i for i, d in notes if d['m'] > 1]}")


if __name__ == "__main__":
    main()

"""The machine marks' frames run-length coded, for the FM-1's Bluetooth build (its flash room: ICON_BITS is 116,736
bytes raw, about 65 KB coded). Reads ICON_BITS from firmware/gen/m2k_icons.h (tools/gen_icons.py's), writes a header
with ICON_RLE (every frame, one after the other) and ICON_RLE_AT (each frame's start, and the end), decoded a frame at
a time where it is drawn (firmware/src/m2k_bt.c icon_frame). Each code byte: 0x00..0x7F, that many + 1 bytes as
they are, following; 0x80..0xBF, (c & 0x3F) + 1 bytes 0x00; 0xC0..0xFF, (c & 0x3F) + 1 bytes 0xFF.

  tools/fm1/gen_icons_rle.py OUT.h          (tools/fm1/build.py runs it for FELUCCA_BLE=1; the host test too)"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def frames():
    t = (ROOT / "firmware" / "gen" / "m2k_icons.h").read_text()
    n = int(re.search(r"#define ICON_COUNT (\d+)", t).group(1))
    f = int(re.search(r"#define ICON_FRAMES (\d+)", t).group(1))
    i = t.index("ICON_BITS[")
    body = t[i:t.index("};", i)]
    raw = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))
    if len(raw) != n * f * 512:
        raise SystemExit(f"gen_icons_rle: ICON_BITS is {len(raw)} bytes, not {n} x {f} x 512")
    return [raw[k * 512:(k + 1) * 512] for k in range(n * f)]


def encode(b):
    o, i, n = bytearray(), 0, len(b)
    while i < n:
        if b[i] in (0, 255):
            v, j = b[i], i
            while j < n and b[j] == v and j - i < 64:
                j += 1
            o.append((0x80 if v == 0 else 0xC0) | (j - i - 1))
            i = j
            continue
        j = i
        while j < n and j - i < 128 and not (b[j] in (0, 255) and j + 1 < n and b[j + 1] == b[j]):
            j += 1
        j = max(j, i + 1)
        o.append(j - i - 1)
        o += b[i:j]
        i = j
    return bytes(o)


def decode(c):
    o, i = bytearray(), 0
    while i < len(c):
        k = c[i]
        i += 1
        if k < 0x80:
            o += c[i:i + k + 1]
            i += k + 1
        else:
            o += bytes([0 if k < 0xC0 else 255]) * ((k & 0x3F) + 1)
    return bytes(o)


def main(out):
    fr = frames()
    data, at = bytearray(), []
    for b in fr:
        e = encode(b)
        if decode(e) != b:
            raise SystemExit("gen_icons_rle: a frame does not decode back")
        at.append(len(data))
        data += e
    at.append(len(data))
    lines = ["/* generated by tools/fm1/gen_icons_rle.py from firmware/gen/m2k_icons.h: do not edit */",
             f"#define ICON_RLE_BYTES {len(data)}u",
             f"static const uint32_t ICON_RLE_AT[{len(at)}] = {{" + ", ".join(map(str, at)) + "};",
             f"static const uint8_t ICON_RLE[{len(data)}] = {{"]
    for k in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in data[k:k + 24]) + ",")
    lines.append("};")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"gen_icons_rle: {len(fr)} frames, {len(fr) * 512} B raw, {len(data)} B coded")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
